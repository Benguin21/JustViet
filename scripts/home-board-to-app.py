#!/usr/bin/env python3
"""Turn the HomeDraft board (a Claude Design .dc.html) into the app's companion files.

  python3 scripts/home-board-to-app.py <HomeDraft.dc.html> src/components/companion

The board comes from the JustViet Design canvas
(https://claude.ai/artifact/5LFnFo85BXbFJk6swP39kQ); download HomeDraft.dc.html from it first.

Writes art.ts (the dish and teacher drawings), HomeView.tsx (the board's markup as JSX,
reading every value from HomeCompanion.renderVals()) and companion.css (the board's styles,
scoped under .jv-root). The board's header, test tips and canvas-only bits are left out.
"""
import json, re, sys
from html.parser import HTMLParser

board_path, out_dir = sys.argv[1], sys.argv[2]
board = open(board_path, encoding="utf-8").read()
lines = board.split("\n")

def find(pred, start=0):
    for i in range(start, len(lines)):
        if pred(lines[i]):
            return i
    raise SystemExit("not found")

# ---------- art ----------
def defs_inner(cls):
    i = find(lambda l: f'class="{cls}"' in l)
    j = find(lambda l: l.startswith("</defs></svg>"), i)
    return "\n".join(lines[i + 1 : j])

menu_art = defs_inner("jv-menu-art")
teach_art = defs_inner("jv-teach-art")
with open(f"{out_dir}/art.ts", "w", encoding="utf-8") as f:
    f.write("// The dish and teacher drawings from the HomeDraft board, as SVG <defs> markup. Each\n")
    f.write("// drawing is a <g id> that the page shows with <use href>: jvArt-{dish}-{back|full|done|front}\n")
    f.write("// and jvT-{teacher}-{back|body|face-*|arms-*}. Generated by home-board-to-app.py; don't edit\n")
    f.write("// by hand.\n\n")
    f.write(f"export const MENU_ART = {json.dumps(menu_art, ensure_ascii=False)};\n\n")
    f.write(f"export const TEACHER_ART = {json.dumps(teach_art, ensure_ascii=False)};\n")

# ---------- markup ----------
main_start = find(lambda l: l.startswith("<main "))
main_end = find(lambda l: l.startswith("</main>"), main_start)
guide_start = find(lambda l: 'class="sr-only"' in l, main_end)
tips_start = find(lambda l: 'value="{{showTips}}"' in l, guide_start)
region = "\n".join(lines[main_start : main_end + 1] + lines[guide_start:tips_start])

ATTR_CASE = {"clippathunits": "clipPathUnits", "maskunits": "maskUnits", "pathlength": "pathLength",
             "preserveaspectratio": "preserveAspectRatio", "viewbox": "viewBox", "onclick": "onClick",
             "tabindex": "tabIndex", "class": "className"}
TAG_CASE = {"clippath": "clipPath"}
CRACK_KEY = re.compile(r"^(crackOff|chipOn|flakeOn|liftOn|crumbOn)_\w+$")
FONT = [("'Baloo 2', sans-serif", "var(--font-heading), sans-serif"), ("'Baloo 2',sans-serif", "var(--font-heading),sans-serif"),
        ("'Nunito', sans-serif", "var(--font-body), sans-serif"), ("'Nunito',sans-serif", "var(--font-body),sans-serif")]

def fonts(s):
    for a, b in FONT:
        s = s.replace(a, b)
    return s

class Node:
    def __init__(self, tag, attrs):
        self.tag, self.attrs, self.kids = tag, attrs, []

class Builder(HTMLParser):
    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.root = Node("#root", [])
        self.stack = [self.root]
    def handle_starttag(self, tag, attrs):
        n = Node(TAG_CASE.get(tag, tag), attrs)
        self.stack[-1].kids.append(n)
        self.stack.append(n)
    def handle_endtag(self, tag):
        n = self.stack.pop()
        assert n.tag.lower() == tag, (n.tag, tag)
    def handle_data(self, data):
        self.stack[-1].kids.append(data)

b = Builder()
b.feed(region)
assert len(b.stack) == 1

HOLE = re.compile(r"\{\{\s*([\w.]+)\s*\}\}")

def expr(e, scope):
    head = e.split(".")[0]
    if head in scope:
        return e
    if CRACK_KEY.match(e):
        return "v.cv." + e
    return "v." + e

def tmpl(s, scope):
    """A string with holes, as a JS expression."""
    parts = HOLE.split(s)
    if len(parts) == 3 and parts[0] == "" and parts[2] == "":
        return expr(parts[1], scope)
    out = ""
    for i, p in enumerate(parts):
        if i % 2:
            out += "${" + expr(p, scope) + "}"
        else:
            out += p.replace("\\", "\\\\").replace("`", "\\`").replace("${", "\\${")
    return "`" + out + "`"

def camel(k):
    return re.sub(r"-([a-z])", lambda m: m.group(1).upper(), k)

def style_obj(s, scope):
    items = []
    for decl in s.split(";"):
        if not decl.strip():
            continue
        k, _, val = decl.partition(":")
        k, val = k.strip(), fonts(val.strip())
        key = json.dumps(k) if k.startswith("--") else camel(k)
        items.append(f"{key}: " + (tmpl(val, scope) if HOLE.search(val) else json.dumps(val, ensure_ascii=False)))
    return "css({ " + ", ".join(items) + " })"

def attr_js(tag, k, val, scope):
    if k.startswith("hint-"):
        return None
    if k == "style":
        return f"style={{{style_obj(val, scope)}}}"
    if k == "ref":
        e = HOLE.search(val).group(1)
        return "ref={tiles[g.id]}" if e == "g.tileRef" else "ref={" + e[: -len("Ref")] + "}"
    name = ATTR_CASE.get(k, k if (k.startswith("aria-") or k.startswith("data-")) else camel(k))
    if tag == "a" and k == "href" and val.startswith("#"):
        val = "/" + val[1:]
    if name in ("tabIndex", "aria-valuemin", "aria-valuemax", "aria-valuenow") and not HOLE.search(val):
        return f"{name}={{{int(val)}}}"
    if HOLE.search(val):
        return f"{name}={{{tmpl(val, scope)}}}"
    return f"{name}={json.dumps(val, ensure_ascii=False)}"

def text_js(t, scope):
    if not t.strip():
        return [] if "\n" in t else ['{" "}']
    out = []
    lead = t[: len(t) - len(t.lstrip())]
    trail = t[len(t.rstrip()) :]
    body = t.strip()
    if lead and "\n" not in lead:
        out.append('{" "}')
    for i, p in enumerate(HOLE.split(body)):
        if i % 2:
            out.append("{" + expr(p, scope) + "}")
        elif p:
            out.append(p if not re.search(r"[{}<>\"'&]", p) else "{" + json.dumps(p, ensure_ascii=False) + "}")
    if trail and "\n" not in trail:
        out.append('{" "}')
    return out

def emit(n, scope, ind):
    pad = "  " * ind
    if isinstance(n, str):
        return [pad + x for x in text_js(n, scope)]
    a = dict(n.attrs)
    if n.tag == "sc-if":
        cond = expr(HOLE.search(a["value"]).group(1), scope)
        body = [y for k in n.kids for y in emit(k, scope, ind + 2)]
        return [pad + "{" + cond + " ? (", pad + "  <>"] + body + [pad + "  </>", pad + ") : null}"]
    if n.tag == "sc-for":
        lst = expr(HOLE.search(a["list"]).group(1), scope)
        var = a["as"]
        body = [y for k in n.kids for y in emit(k, scope | {var}, ind + 2)]
        return [pad + "{" + lst + f".map(({var}, {var}i) => (", pad + f"  <Fragment key={{{var}i}}>"] + body + [pad + "  </Fragment>", pad + "))}"]
    tag = "Link" if n.tag == "a" else n.tag
    attrs = [x for x in (attr_js(n.tag, k, v or "", scope) for k, v in n.attrs) if x]
    head = pad + "<" + tag + ("" if not attrs else " " + " ".join(attrs))
    kids = [y for k in n.kids for y in emit(k, scope, ind + 1)]
    if not kids:
        return [head + " />"]
    if len(kids) == 1 and len(head) + len(kids[0].strip()) < 150:
        return [head + ">" + kids[0].strip() + "</" + tag + ">"]
    return [head + ">"] + kids + [pad + "</" + tag + ">"]

body = []
for k in b.root.kids:
    body += emit(k, set(), 3)

header = '''// The homepage's markup, converted from the HomeDraft board on the JustViet design canvas
// (https://claude.ai/artifact/5LFnFo85BXbFJk6swP39kQ) by home-board-to-app.py. It follows the
// board one to one (classes, inline styles, structure) so the two can be compared side by side;
// HomeCompanion works out every value it shows. The board's header is the app's AppHeader.
import Link from "next/link";
import { Fragment, type CSSProperties } from "react";
import { MENU_ART, TEACHER_ART } from "./art";
import type { HomeRefs, HomeVals } from "./HomeCompanion";

const css = (o: Record<string, string | number>) => o as CSSProperties;
const HIDDEN_ART = css({ position: "absolute", width: 0, height: 0, overflow: "hidden" });

export function HomeView({ v, at }: { v: HomeVals; at: HomeRefs }) {
  const { root, talk, stage, dragon, guide, tiles } = at;
  return (
    <div
      className="jv-root"
      ref={root}
      style={css({ flex: "1 0 auto", display: "flex", flexDirection: "column", background: "#fffaf1", color: "#4a2f22", fontFamily: "var(--font-body), sans-serif", lineHeight: "normal" })}
    >
      <svg className="jv-menu-art" width="0" height="0" aria-hidden="true" focusable="false" style={HIDDEN_ART}>
        <defs dangerouslySetInnerHTML={{ __html: MENU_ART }} />
      </svg>
      <svg className="jv-teach-art" width="0" height="0" aria-hidden="true" focusable="false" style={HIDDEN_ART}>
        <defs dangerouslySetInnerHTML={{ __html: TEACHER_ART }} />
      </svg>
'''
footer = '''    </div>
  );
}
'''
with open(f"{out_dir}/HomeView.tsx", "w", encoding="utf-8") as f:
    f.write(header + "\n".join(body) + "\n" + footer)

# ---------- styles ----------
s0 = find(lambda l: l.strip() == "<style>", find(lambda l: l.strip() == "<helmet>"))
s1 = find(lambda l: l.strip() == "</style>", s0)
css = "\n".join(lines[s0 + 1 : s1])

def top_level_split(s, sep=","):
    out, depth, cur = [], 0, ""
    for ch in s:
        if ch in "([":
            depth += 1
        elif ch in ")]":
            depth -= 1
        if ch == sep and depth == 0:
            out.append(cur); cur = ""
        else:
            cur += ch
    out.append(cur)
    return out

DROP = re.compile(r"^(body|\.test-tips|\.tips-)")
def scope_css(text):
    out, i = [], 0
    while i < len(text):
        if text[i].isspace():
            out.append(text[i]); i += 1; continue
        if text.startswith("/*", i):
            j = text.index("*/", i) + 2
            out.append(text[i:j]); i = j; continue
        j = text.index("{", i)
        sel = text[i:j].strip()
        # matching brace
        depth, k = 0, j
        while True:
            if text[k] == "{": depth += 1
            elif text[k] == "}":
                depth -= 1
                if depth == 0: break
            k += 1
        block = text[j + 1 : k]
        if sel.startswith("@keyframes"):
            out.append(f"{sel}{{{block}}}")
        elif sel.startswith("@media"):
            out.append(f"{sel}{{{scope_css(block)}}}")
        else:
            sels = [x.strip() for x in top_level_split(sel)]
            sels = [x for x in sels if not DROP.match(x)]
            if sels:
                sels = [x if x.startswith(".jv-root") else ":where(.jv-root) " + x for x in sels]
                out.append(",".join(sels) + "{" + block + "}")
        i = k + 1
    return "".join(out)

css = fonts(css).replace(".hidden", ".unshown")
css = scope_css(css)
css = re.sub(r"\n{3,}", "\n\n", css)
with open(f"{out_dir}/companion.css", "w", encoding="utf-8") as f:
    f.write("/* Rồng Con's homepage: the HomeDraft board's styles, scoped under .jv-root so nothing\n")
    f.write("   leaks to other pages (generated by home-board-to-app.py). */\n")
    f.write(css.strip() + "\n")
print("ok")
